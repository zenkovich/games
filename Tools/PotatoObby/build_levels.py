def normalize(level, index):
    rows = level["rows"]
    assert len(rows) <= ROWS, f"level {index+1}: {len(rows)} rows"
    out = []
    for r in rows:
        assert len(r) <= COLS, f"level {index+1}: row '{r}' is {len(r)} wide"
        bad = set(r) - TILES
        assert not bad, f"level {index+1}: unknown tiles {bad}"
        out.append(r.ljust(COLS, "."))
    out = ["." * COLS] * (ROWS - len(out)) + out
    joined = "".join(out)
    assert joined.count("S") == 1 and joined.count("E") == 1, f"level {index+1}: need one S and one E"
    level = dict(level); level["rows"] = out
    return level

