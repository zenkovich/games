"""Writes Tools/WordFall/CssScreen/campaign.js: the campaign of Assets/WordFall/campaign.json as a
script global, so the HTML prototype (play.html) can read it from file:// where fetch is blocked."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
levels = json.load(open(ROOT / "Assets" / "WordFall" / "campaign.json", encoding="utf-8"))
out = ROOT / "Tools" / "WordFall" / "CssScreen" / "campaign.js"
out.write_text("// generated by Tools/WordFall/build_play_data.py from Assets/WordFall/campaign.json\n"
               "WordFallCampaignData = " + json.dumps(levels, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
print("wrote", out, len(levels), "levels")
